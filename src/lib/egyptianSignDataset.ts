export const EGYPTIAN_SIGN_DATASET_COUNT = EGYPTIAN_SIGN_DATASET.length;

/**
 * Compact dataset reference injected into Gemini Vision & Sentence Composer prompts
 * so the model grounds predictions in the 56 Mendeley Egyptian Sign Language classes
 * plus body location & dual-hand context.
 */
export const EGYPTIAN_SIGN_DATASET_PROMPT = EGYPTIAN_SIGN_DATASET.map(
  (entry) =>
    `${entry.arabicWord} [${entry.slug}, ${entry.twoHanded ? '2-hands' : '1-hand'}, zone:${entry.bodyAnchor}, sign:${entry.mappedSignId}]`
).join(' | ');

export function findEgyptianSignEntry(query: string): EgyptianSignDatasetEntry | undefined {
  const norm = query.trim().toLowerCase();
  if (!norm) return undefined;
  return EGYPTIAN_SIGN_DATASET.find(
    (entry) =>
      entry.slug.toLowerCase() === norm ||
      entry.arabicWord.toLowerCase() === norm ||
      entry.englishWord.toLowerCase() === norm
  );
}
